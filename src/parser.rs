// Парсер HTML-страницы с вакансиями.
//
// В реальном проекте здесь бы использовались HTTP-клиент и HTML-парсер (например, `reqwest` + `scraper`).
// В этой фазе важно показать, как ownership и borrowing применяются в сигнатурах и теле функций.

use crate::domain::Job;

/// Парсит HTML и возвращает список вакансий.
///
/// Обратите внимание на сигнатуру:
///  - `html: &str` — мы *заимствуем* строку, не забирая владение и не создавая `String`.
///  - `Vec<Job>` — возвращаем вектор, который *владеет* всеми `Job`.
///
/// Причина такого решения:
///  - HTML уже где-то в памяти (например, буфер HTTP-ответа) — нет смысла копировать его.
///  - Но сами вакансии (`Job`) должны жить дольше, чем HTML (его буфер может быть освобождён).
pub fn parse_jobs(_html: &str) -> Vec<Job> {
    // В этой демо-реализации мы не делаем настоящий парсинг.
    // Вместо этого покажем, как мы "собираем" `Job` из каких-то &str и превращаем их в `String`.

    // Обычно на этом месте был бы вызов реального парсера, который итерируется по элементам:
    // for element in document.select(&job_card_selector) { ... }
    // Каждый `element` даёт набор фрагментов текста `&str`, которые нужно собрать в `String`.

    // Для иллюстрации: "распарсим" HTML на два Job, как будто мы их достали из DOM.
    let mut jobs = Vec::new();

    // Пример 1: юниор Rust разработчик.
    // Мы начинаем с &str (например, вернутое парсером), а затем конвертируем в `String`.
    let title_1: &str = "Junior Rust Developer";
    let company_1: &str = "Acme Corp";
    let tech_1: [&str; 3] = ["Rust", "Tokio", "SQL"];

    jobs.push(Job {
        // Здесь `to_string()` создаёт новый `String`, копируя содержимое &str.
        // Такая копия оправдана, потому что `Job` должен жить дольше, чем исходный &str.
        title: title_1.to_string(),
        company: company_1.to_string(),
        // Из массива &str делаем `Vec<String>`, по одному move каждого `String` в вектор.
        tech_stack: tech_1.iter().map(|s| (*s).to_string()).collect(),
    });

    // Пример 2: стажёр backend engineer на Rust.
    let title_2: &str = "Intern Backend Engineer";
    let company_2: &str = "Startup X";
    let tech_2: [&str; 3] = ["Rust", "Actix", "Postgres"];

    jobs.push(Job {
        title: title_2.to_string(),
        company: company_2.to_string(),
        tech_stack: tech_2.iter().map(|s| (*s).to_string()).collect(),
    });

    // В реальном парсере место, где мы собираем текст тайтла, выглядело бы так:
    //
    // let title = element
    //     .select(&title_selector)
    //     .next()
    //     .map(|el| el.text().collect::<String>())
    //     .unwrap_or_default();
    //
    // Метод `text()` возвращает итератор по &str, и `collect::<String>()` неизбежно создаёт
    // новую строку — без этого мы не сможем склеить фрагменты.

    // Возвращаем `jobs` по move — вызывающая сторона теперь владеет этим вектором.
    jobs
}

/// Удаляет дубликаты вакансий.
///
/// Сигнатура подчёркивает владение:
///  - `jobs: Vec<Job>` — функция *забирает* вектор целиком (move).
///  - Возвращаем новый `Vec<Job>`, где все элементы — те же самые `Job`, но без дублей.
pub fn dedup(jobs: Vec<Job>) -> Vec<Job> {
    use std::collections::HashSet;

    // Мы создаём новый вектор и множества для проверки уникальности.
    // Старый `jobs` мы не можем больше использовать (он move'нут в эту функцию).
    let mut seen = HashSet::new();
    let mut unique = Vec::new();

    // `into_iter()` *перемещает* каждый `Job` из исходного вектора.
    // После этого элементы принадлежат не вектору `jobs`, а переменной `job` в цикле.
    for job in jobs.into_iter() {
        // Чтобы проверить, встречалась ли вакансия, мы используем кортеж ключевых полей.
        //
        // Важно: мы создаём *владейщую* копию ключа через `String::clone()`.
        // Это нужен, чтобы `HashSet` мог хранить ключ дольше, чем живёт `job`,
        // который мы затем перемещаем в `unique`.
        //
        // Такая копия — осознанный обмен: небольшие аллокации памяти ради простой,
        // безопасной логики dedup. В реальном проекте можно оптимизировать стратегию
        // ключей под конкретные требования.
        let key = (job.title.clone(), job.company.clone());

        if seen.insert(key) {
            // `job` move'ится в новый вектор `unique`.
            // Строки внутри `job` *не* клонируются здесь, мы просто переносим владение.
            unique.push(job);
        }
        // Если `insert` вернул false, job просто дропается, и память освобождается.
    }

    unique
}


